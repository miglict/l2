# -*- coding: cp1251 -*-
from math import sqrt

# Ввод данных
R = float(input('Введите радиус R (или нажмите Enter для R=1): ') or '1')

print('Введите координаты точки:')
x = float(input('X='))
y = float(input('Y='))

# Вычисляем расстояние от центра до точки в квадрате
dist_sq = x**2 + y**2

# Проверка условий
# 1. Точка должна быть внутри круга (или на границе)
inside_circle = dist_sq <= R**2

# 2. Точка должна быть во II четверти (x<=0, y>=0) или в IV четверти (x>=0, y<=0)
# Это эквивалентно тому, что x и y имеют разные знаки (или один из них 0)
correct_quadrant = (x <= 0 and y >= 0) or (x >= 0 and y <= 0) #отвечает за то находится ли точка в нужной четверти

if inside_circle and correct_quadrant:
    print(f"Точка ({x}, {y}) попадает в область.")
else:
    print(f"Точка ({x}, {y}) не попадает в область.")